/** True when the name is a recognised environment global, not app config. */
export function isEnvironmentGlobal(name: string): boolean {
  return NODE_GLOBALS.has(name);
}

/**
 * True when a script looks like Node/CommonJS rather than browser code.
 *
 * Heuristic: uses `require(`/`module.exports`/`process.` and never touches
 * `document` or `window` as globals. Used only to avoid nonsense findings on
 * server bundles; a single positive browser marker keeps a file in scope.
 */
export function looksLikeNodeModule(code: string): boolean {
  const nodeMarkers = /\brequire\s*\(|\bmodule\.exports\b|\bexports\.[A-Za-z_$]|\bprocess\.(?:env|argv|platform|version|cwd|nextTick)\b|\b__dirname\b|\b__filename\b/;
  const browserMarkers = /\bdocument\.|\bwindow\.|addEventListener\s*\(|localStorage\b|querySelector/;
  return nodeMarkers.test(code) && !browserMarkers.test(code);
}
